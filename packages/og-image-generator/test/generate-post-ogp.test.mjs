import assert from 'node:assert/strict';
import { mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import test from 'node:test';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { generatePostOgpPng } from '../dist/index.js';
import {
  getPostOgpTitleStyle,
  layoutPostOgpTitle,
  POST_OGP_TITLE_WIDTH,
} from '../dist/title-layout.js';
import { createElement as h } from 'react';
import satori from 'satori';
import { Resvg } from '@resvg/resvg-js';

const fonts = [
  {
    name: 'Noto Sans JP',
    weight: 700,
    data: await readFile(new URL('../assets/NotoSansJP-Bold.otf', import.meta.url)),
  },
];

async function renderTitle(title) {
  const layout = await layoutPostOgpTitle(title, fonts);
  const lines = new Map();
  const svg = await satori(
    h('div', { lang: 'ja-JP', style: getPostOgpTitleStyle(layout.fontSize) }, layout.title),
    { width: POST_OGP_TITLE_WIDTH, fonts, embedFont: false },
  );
  const ink = new Resvg(
    await satori(
      h('div', { lang: 'ja-JP', style: getPostOgpTitleStyle(layout.fontSize) }, layout.title),
      { width: POST_OGP_TITLE_WIDTH, fonts },
    ),
  ).innerBBox();
  assert.ok(
    ink.x >= 0 && ink.x + ink.width <= POST_OGP_TITLE_WIDTH,
    `${title}: ink exceeds the title width`,
  );
  for (const [, attributes, text] of svg.matchAll(/<text ([^>]*)>(.*?)<\/text>/gs)) {
    const attr = (name) => Number(attributes.match(new RegExp(`${name}="([^"]*)"`))?.[1]);
    const x = attr('x');
    const right = x + attr('width');
    const y = attr('y');
    const line = lines.get(y) ?? { text: '', width: 0 };
    line.text += text;
    line.width = Math.max(line.width, right);
    lines.set(y, line);
  }
  return { layout, lines: [...lines.values()] };
}

function readPngSize(buffer) {
  return {
    width: buffer.readUInt32BE(16),
    height: buffer.readUInt32BE(20),
  };
}

test('generates a PNG for a short title', async () => {
  const png = Buffer.from(
    await generatePostOgpPng({
      title: 'About',
      category: 'Other',
      publishedAt: new Date('2020-11-23T00:00:00.000Z'),
    }),
  );

  assert.equal(png.subarray(0, 8).toString('hex'), '89504e470d0a1a0a');
  assert.deepEqual(readPngSize(png), { width: 1200, height: 630 });
});

